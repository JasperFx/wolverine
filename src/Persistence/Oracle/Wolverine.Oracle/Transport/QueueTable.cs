using Weasel.Oracle;
using Weasel.Oracle.Tables;
using Wolverine.RDBMS;

namespace Wolverine.Oracle.Transport;

internal class QueueTable : Table
{
    internal const string QueueOrderColumn = "queue_order";

    public QueueTable(OracleTransport parent, string tableName) : base(
        new OracleObjectName(parent.TransportSchemaName.ToUpperInvariant(), tableName.ToUpperInvariant()))
    {
        // Never drop the opt-in ordering column or its index if the option is later turned off
        AddOnlyMigrations = true;

        AddColumn<Guid>(DatabaseConstants.Id).AsPrimaryKey();
        AddColumn(DatabaseConstants.Body, "BLOB").NotNull();
        AddColumn(DatabaseConstants.MessageType, "VARCHAR2(500)").NotNull();
        AddColumn<DateTimeOffset>(DatabaseConstants.KeepUntil);
        AddColumn<DateTimeOffset>("timestamp").DefaultValueByExpression("SYSTIMESTAMP AT TIME ZONE 'UTC'");

        // Keep the released schema as the default. The identity tie-breaker is an opt-in schema
        // change for rows that share a timestamp.
        if (parent.EnableDeterministicQueueOrdering)
        {
            AddColumn(BuildQueueOrderColumn());

            // There is no legacy timestamp index on this table, so this is the only one added
            Indexes.Add(new IndexDefinition($"idx_{tableName}_ts_order")
            {
                Columns = ["timestamp", QueueOrderColumn]
            });
        }
    }

    /// <summary>
    ///     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY. Oracle assigns a distinct value to every
    ///     existing row when the column is added to a populated table, so the migration is additive.
    /// </summary>
    internal static TableColumn BuildQueueOrderColumn()
    {
        return new TableColumn(QueueOrderColumn, "NUMBER(19)") { IsAutoNumber = true };
    }
}
