    /// <summary>A one-slice board whose only example is <paramref name="scenario"/>, as a reader with more to say than emlang would lower it.</summary>
    private static GeneratedSpecs billing(ScenarioModel scenario, string? sliceType = null, params EmlangStep[] steps)
    {
        var chapter = new EmlangChapter("Billing", steps.Length == 0 ? [IssueInvoice, InvoiceIssued] : steps, [scenario.ToEmlangTest()])
            { SliceType = sliceType };
        var board = new EmlangBoard([chapter]);
        var model = EmlangImport.ToCurated(board, "Billing").Model;
        return EmlangSpecWriter.Write(board, model, "Billing");
    }

