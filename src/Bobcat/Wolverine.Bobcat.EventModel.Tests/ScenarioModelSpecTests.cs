    [Fact]
    public void a_refusal_is_written_by_its_kind()
    {
        string refusal(RefusalKind kind, ScenarioAct act) => billing(new ScenarioModel("Refused")
        {
            GivenEvents = [AnIssuedInvoice],
            Act = act,
            Outcomes = [new Refusal("Amount must be positive", kind, ["inv-1"])],
        }).AllCode();

        var message = new MessageReceived("Issue invoice", values(("invoice id", "inv-1"), ("amount", "-1")));
        refusal(RefusalKind.Validation, message).ShouldContain("ThenValidationFails(\"Amount must be positive\");");
        refusal(RefusalKind.Refused, message).ShouldContain("ThenRefusedWith(\"Amount must be positive\", theInvoice);");
        refusal(RefusalKind.ProblemDetails, message).ShouldContain("ThenRefusedWith(\"Amount must be positive\", theInvoice);");
        refusal(RefusalKind.ProblemDetails, message).ShouldNotContain("ThenRefusedWithProblem");
        refusal(RefusalKind.NotFound, message).ShouldContain("// The model says what the command addresses is not found\n        ThenRefusedWith(\"Amount must be positive\", theInvoice);");

        var http = new HttpRequest("POST", "/invoices/{invoiceId}", "Issue invoice", values(("invoice id", "inv-1"), ("amount", "-1")))
            { RouteValues = values(("invoice id", "inv-1")) };
        refusal(RefusalKind.NotFound, http).ShouldContain("ThenNotFound();");

        // A refusal naming values holds the same way for an endpoint, through its ProblemDetails; one naming none is the
        // ProblemDetails answer itself
        refusal(RefusalKind.ProblemDetails, http).ShouldContain("ThenRefusedWith(\"Amount must be positive\", theInvoice);");
        refusal(RefusalKind.Refused, http).ShouldContain("ThenRefusedWith(\"Amount must be positive\", theInvoice);");

        var unnamed = billing(new ScenarioModel("Refused")
        {
            GivenEvents = [AnIssuedInvoice],
            Act = http,
            Outcomes = [new Refusal("Amount must be positive", RefusalKind.Refused, [])],
        }).AllCode();
        unnamed.ShouldContain("await ThenRefusedWithProblem(Specify<ProblemDetails>().With(x => x.Detail, \"Amount must be positive\"));");
    }

